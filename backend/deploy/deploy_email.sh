# ---- SMTP / email env vars (idempotent: replaces existing keys) ----
add_env() {
  local key="$1" val="$2"
  sed -i "/^$key=/d" .env
  printf '%s=%s\n' "$key" "$val" >> .env
}
# only set if missing — never clobber an existing value
add_env_keep() {
  local key="$1" val="$2"
  grep -q "^$key=" .env || printf '%s=%s\n' "$key" "$val" >> .env
}
