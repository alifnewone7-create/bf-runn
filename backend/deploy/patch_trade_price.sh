# =========================================================================
# Binary Fund Global — VPS backend PATCH (trade entry/exit price accuracy)
# =========================================================================
# What this patch changes:
#   1. market.py         → new Engine.price_at(symbol, ts): price of the last
#                          tick at/at-or-before a given instant.
#   2. trade_routes.py   → place_trade accepts `clientTickT` (the timestamp of
#                          the tick the trader was looking at) and takes the
#                          entry price from the server's OWN tick history at
#                          that instant. No 1-tick drift, so the chart's entry
#                          dot lands on the exact price and never shifts.
#   3. ws_routes.py      → settlement now reads the exit price AT THE EXPIRY
